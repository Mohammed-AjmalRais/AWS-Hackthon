/**
 * Returns all available Indian States and Union Territories
 */
export function getAllStates(): string[] {
  return Object.keys(INDIA_STATES_AND_DISTRICTS);
}

/**
 * Returns the list of districts for a specified state.
 * Returns empty array or central regions if state is not matched.
 */
export function getDistrictsForState(stateName: string): string[] {
  if (!stateName) return [];
  if (INDIA_STATES_AND_DISTRICTS[stateName]) {
    return INDIA_STATES_AND_DISTRICTS[stateName];
  }

  // Case-insensitive fallback
  const foundKey = Object.keys(INDIA_STATES_AND_DISTRICTS).find(
    (k) => k.toLowerCase() === stateName.trim().toLowerCase()
  );

  return foundKey ? INDIA_STATES_AND_DISTRICTS[foundKey] : [];
}

/**
 * Returns the top 4-6 prominent districts for quick pill selection
 */
export function getTopDistrictsForState(stateName: string): string[] {
  const districts = getDistrictsForState(stateName);
  if (!districts || districts.length === 0) return [];
  return districts.slice(0, Math.min(6, districts.length));
}
